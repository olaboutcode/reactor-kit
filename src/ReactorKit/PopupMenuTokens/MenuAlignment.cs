namespace Reactor.Kit.PopupMenuTokens;

/// <summary>
/// Which edge of the anchor the panel lines up with.
/// </summary>
public enum MenuAlignment
{
    /// <summary>
    /// The panel's trailing edge lines up with the anchor's trailing edge.
    /// </summary>
    Trailing,

    /// <summary>
    /// The panel's leading edge lines up with the anchor's leading edge.
    /// </summary>
    Leading,

    /// <summary>
    /// The panel is centered on the anchor.
    /// </summary>
    Center,
}
